// ScopedPatterns lists every route the scope table and the list of routes outside every space
// name, so a check can find a line that outlived its route.
func ScopedPatterns() []string {
	out := make([]string, 0, len(routeScopes)+len(spaceBoundless))
	for pattern := range routeScopes {
		out = append(out, pattern)
	}
	for pattern := range spaceBoundless {
		out = append(out, pattern)
	}
	slices.Sort(out)
	return out
}
